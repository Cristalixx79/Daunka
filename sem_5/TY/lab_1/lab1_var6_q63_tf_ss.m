%% Вопрос 6.3. Передаточная функция и модель в пространстве состояний
%  Часть 1: пример из методички   6y''' + 4y'' + y' + 3y = 2u' + 5u
%  Часть 2: уравнение варианта 6  x''' + 0*x'' + 5x' + 15x = 15y
%  Часть 3: характеристики варианта 6 (Приложение А: pole, zero, step, impulse, bode, nyquist)
%  Нужен Control System Toolbox (tf, ss, pole, zero, step, ...).

clear; clc; close all;

%% ================= ЧАСТЬ 1. Пример из методички =================
% Преобразование Лапласа при нулевых НУ (d/dt <-> s):
%   (6s^3 + 4s^2 + s + 3) Y(s) = (2s + 5) U(s)
num1 = [2 5];
den1 = [6 4 1 3];
W1 = tf(num1, den1)                 % W(s) = (2s + 5) / (6s^3 + 4s^2 + s + 3)

p1 = pole(W1)                       % полюса:  -1  и  (1 +/- j*sqrt(17))/6
z1 = zero(W1)                       % ноль:    -2.5
fprintf('Гурвиц (кубический): a2*a1 - a3*a0 = %g, устойчива: %d\n\n', ...
        4*1 - 6*3, all(real(p1) < 0));

% Пространство состояний (каноническая управляемая форма).
% Вводим вспомогательную переменную z:   6z''' + 4z'' + z' + 3z = u,   y = 5z + 2z'
% Тогда x1 = z, x2 = z', x3 = z'':
%   x1' = x2
%   x2' = x3
%   x3' = (-3*x1 - 1*x2 - 4*x3 + u) / 6
%   y   = 5*x1 + 2*x2
A1 = [0, 1, 0;
      0, 0, 1;
      -den1(4)/den1(1), -den1(3)/den1(1), -den1(2)/den1(1)];
B1 = [0; 0; 1/den1(1)];
C1 = [num1(2), num1(1), 0];
D1 = 0;
disp('Матрицы модели x'' = A*x + B*u,  y = C*x + D*u :');
A1, B1, C1, D1
sys1 = ss(A1, B1, C1, D1);

Wcheck1 = tf(sys1)                  % совпадает с W1 (числитель и знаменатель поделены на 6)

%% ================= ЧАСТЬ 2. Вариант 6 =================
a0 = 15;  a1 = 5;  a2 = 0;  a3 = 1;  b = 15;

% Передаточная функция W(s) = X(s)/Y(s) при нулевых НУ:
%   (a3*s^3 + a2*s^2 + a1*s + a0) X(s) = b Y(s)
den6 = [a3 a2 a1 a0];
num6 = b;
W6 = tf(num6, den6)                 % W(s) = 15 / (s^3 + 5s + 15)

p6 = pole(W6)                       % -1.8114,  0.9057 +/- 2.7314i
z6 = zero(W6)                       % нулей нет (пустой вектор)

% Пространство состояний: x1 = x, x2 = x', x3 = x''
%   x1' = x2;   x2' = x3;   x3' = (b*y - a0*x1 - a1*x2 - a2*x3)/a3;   выход = x1
A6 = [0, 1, 0;
      0, 0, 1;
      -a0/a3, -a1/a3, -a2/a3];
B6 = [0; 0; b/a3];
C6 = [1, 0, 0];
D6 = 0;
disp('Вариант 6: матрицы модели x'' = A*x + B*y,  выход = C*x + D*y :');
A6, B6, C6, D6
sys6 = ss(A6, B6, C6, D6);

Wcheck6 = tf(sys6)                  % должна совпасть с W6
eigA6 = eig(A6)                     % собственные числа A = полюса W(s)

% Критерий Гурвица для a3*s^3 + a2*s^2 + a1*s + a0:  все ai > 0 и a2*a1 > a3*a0
hur = a2*a1 - a3*a0;
fprintf('Гурвиц: a2*a1 - a3*a0 = %g\n', hur);
if all(real(p6) < 0)
    disp('Вариант 6: система устойчива.');
else
    disp('Вариант 6: система НЕУСТОЙЧИВА (a2 = 0 и a2*a1 < a3*a0).');
end
fprintf('Статический коэффициент передачи W(0) = %g\n', b/a0);

%% ================= ЧАСТЬ 3. Характеристики варианта 6 =================
Tend = 5;

figure('Name', 'Вариант 6: h(t) и w(t)', 'NumberTitle', 'off');
subplot(1, 2, 1);
step(W6, Tend);     grid on;  title('Переходная характеристика h(t)');
subplot(1, 2, 2);
impulse(W6, Tend);  grid on;  title('Импульсная переходная функция w(t)');

figure('Name', 'Вариант 6: ЛАЧХ и ЛФЧХ', 'NumberTitle', 'off');
bode(W6);           grid on;

figure('Name', 'Вариант 6: АФЧХ (Найквист)', 'NumberTitle', 'off');
nyquist(W6);        grid on;

